-- Execute with causal schema owner independently of v2_flyway_schema_history.
-- Existing causal facts are preserved; never drops or rewrites historical rows.
CREATE TABLE IF NOT EXISTS claim_table (
    claim_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cause_standard varchar(255) NOT NULL,
    effect_standard varchar(255) NOT NULL,
    claim_hash varchar(64) NOT NULL UNIQUE,
    created_at timestamp NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS paper_claim_table (
    record_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    paper_id varchar(100) NOT NULL,
    claim_id bigint NOT NULL REFERENCES claim_table (claim_id),
    sign_of_impact varchar(50) NOT NULL,
    type_of_relationship varchar(100) NOT NULL,
    claim text NOT NULL,
    cause text NOT NULL,
    cause_score numeric(4, 3),
    effect text NOT NULL,
    effect_score numeric(4, 3),
    evidence text NOT NULL,
    causal_inference_method varchar(100) NOT NULL,
    evidence_method_other_description text,
    is_main_contribution boolean NOT NULL,
    level_of_tentativeness varchar(50),
    sources_of_exogenous_variation text,
    statistical_significance varchar(100),
    created_at timestamp NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS stw_label (
    stw_id varchar(128),
    label_en varchar(255) NOT NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_causal_claim_hash ON claim_table (claim_hash);
CREATE INDEX IF NOT EXISTS idx_paper_claim_paper_id ON paper_claim_table (paper_id);
CREATE INDEX IF NOT EXISTS idx_paper_claim_claim_id ON paper_claim_table (claim_id);
CREATE INDEX IF NOT EXISTS idx_stw_label_en_lower ON stw_label (lower(label_en));

DO $$
DECLARE
    claim_next bigint;
    record_next bigint;
BEGIN
    IF EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_schema = current_schema() AND table_name = 'claim_table'
          AND column_name = 'claim_id' AND is_identity = 'NO' AND column_default IS NULL
    ) THEN
        ALTER TABLE claim_table ALTER COLUMN claim_id ADD GENERATED BY DEFAULT AS IDENTITY;
    END IF;
    SELECT COALESCE(MAX(claim_id), 0) + 1 INTO claim_next FROM claim_table;
    IF pg_get_serial_sequence('claim_table', 'claim_id') IS NOT NULL THEN
        PERFORM setval(pg_get_serial_sequence('claim_table', 'claim_id'), GREATEST(claim_next, 1), false);
    END IF;

    IF EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_schema = current_schema() AND table_name = 'paper_claim_table'
          AND column_name = 'record_id' AND is_identity = 'NO' AND column_default IS NULL
    ) THEN
        ALTER TABLE paper_claim_table ALTER COLUMN record_id ADD GENERATED BY DEFAULT AS IDENTITY;
    END IF;
    SELECT COALESCE(MAX(record_id), 0) + 1 INTO record_next FROM paper_claim_table;
    IF pg_get_serial_sequence('paper_claim_table', 'record_id') IS NOT NULL THEN
        PERFORM setval(pg_get_serial_sequence('paper_claim_table', 'record_id'), GREATEST(record_next, 1), false);
    END IF;

    IF NOT EXISTS (SELECT 1 FROM paper_claim_table GROUP BY paper_id, cause, effect HAVING count(*) > 1) THEN
        CREATE UNIQUE INDEX IF NOT EXISTS uq_causal_paper_relation ON paper_claim_table (paper_id, cause, effect);
    END IF;
END $$;

CREATE TABLE IF NOT EXISTS causal_publication_receipt (
    publication_id varchar(64) PRIMARY KEY,
    payload_hash varchar(64) NOT NULL,
    work_id varchar(255) NOT NULL,
    row_count integer NOT NULL CHECK (row_count >= 0),
    applied_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS causal_dataset_revision (
    id integer PRIMARY KEY CHECK (id = 1),
    revision bigint NOT NULL DEFAULT 0,
    updated_at timestamptz NOT NULL DEFAULT now()
);

INSERT INTO causal_dataset_revision (id, revision) VALUES (1, 0) ON CONFLICT (id) DO NOTHING;
