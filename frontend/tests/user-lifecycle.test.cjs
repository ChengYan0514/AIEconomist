const assert = require("node:assert/strict")
const { test } = require("node:test")
const { login, withBrowser } = require("./browser.cjs")

async function signIn(page, username, password) {
  await page.getByLabel("用户名").fill(username)
  await page.getByLabel("密码", { exact: true }).fill(password)
  await page.getByRole("button", { name: "登录管理端" }).click()
}

async function changeTemporaryPassword(page, temporary, password) {
  await page.getByRole("heading", { name: "设置个人密码" }).waitFor()
  await page.getByLabel("临时密码", { exact: true }).fill(temporary)
  await page.getByLabel("新密码", { exact: true }).fill(password)
  await page.getByRole("button", { name: "保存密码" }).click()
}

async function createUser(admin, username, role) {
  await admin.getByRole("button", { name: "新建用户" }).click()
  const form = admin.getByRole("dialog")
  await form.getByLabel("用户名", { exact: true }).fill(username)
  await form.getByLabel("显示名称", { exact: true }).fill("账号生命周期验收")
  await form.getByLabel("角色", { exact: true }).selectOption(role)
  await form.getByRole("button", { name: "创建账号" }).click()
  const temporary = await form.getByRole("textbox", { name: "临时密码" }).inputValue()
  await form.getByRole("button", { name: "完成" }).click()
  return temporary
}

test("系统管理员停用、恢复及重置用户，用户先设置个人密码才能访问论文", () => withBrowser(async (browser, url) => {
  const admin = await browser.newPage()
  admin.setDefaultTimeout(5000)
  await admin.goto(url + "/users")
  await login(admin)
  const username = "browser.lifecycle"
  const originalTemporary = await createUser(admin, username, "READ_ONLY")
  const reader = await browser.newPage()
  reader.setDefaultTimeout(5000)
  await reader.goto(url + "/papers")
  await signIn(reader, username, originalTemporary)
  await changeTemporaryPassword(reader, originalTemporary, "original-personal-password")
  await signIn(reader, username, "original-personal-password")
  await reader.getByRole("heading", { name: "论文库" }).waitFor()

  const row = admin.getByRole("row", { name: /browser.lifecycle/ })
  const dialog = admin.getByRole("dialog")
  await row.getByRole("button", { name: /停用/ }).click()
  await dialog.getByRole("button", { name: "确认停用" }).click()
  await row.getByRole("button", { name: /恢复/ }).waitFor()
  await reader.reload()
  await reader.getByRole("heading", { name: "登录", exact: true }).waitFor()
  await signIn(reader, username, "original-personal-password")
  await reader.getByText("用户名或密码错误").waitFor()

  await row.getByRole("button", { name: /恢复/ }).click()
  await dialog.getByRole("button", { name: "确认恢复" }).click()
  await row.getByText("启用", { exact: true }).waitFor()
  await signIn(reader, username, "original-personal-password")
  await reader.getByRole("heading", { name: "论文库" }).waitFor()

  await row.getByRole("button", { name: /重置密码/ }).click()
  assert.equal(await dialog.getByRole("textbox", { name: "临时密码" }).count(), 0)
  await dialog.getByRole("button", { name: "确认重置" }).click()
  const temporary = await dialog.getByRole("textbox", { name: "临时密码" }).inputValue()
  assert.ok(temporary.length >= 12)
  await dialog.getByRole("button", { name: "完成" }).click()
  assert.equal(await admin.getByRole("textbox", { name: "临时密码" }).count(), 0)
  await reader.reload()
  await signIn(reader, username, temporary)
  await changeTemporaryPassword(reader, temporary, "replacement-personal-password")
  await signIn(reader, username, "replacement-personal-password")
  await reader.getByRole("heading", { name: "论文库" }).waitFor()

  await admin.goto(url + "/audit?objectId=" + username)
  await admin.getByRole("button", { name: "恢复用户" }).waitFor()
  await admin.getByRole("button", { name: "停用用户" }).waitFor()
  await admin.getByRole("button", { name: "重置用户密码" }).click()
  const event = admin.getByRole("region", { name: "事件详情" })
  await event.getByText("需设置个人密码", { exact: true }).waitFor()
  assert.equal(await event.getByText(temporary, { exact: true }).count(), 0)
  await event.getByRole("link", { name: "查看用户" }).click()
  await row.getByText(username, { exact: true }).waitFor()
}))

test("管理员重置自己的密码后仍可查看一次临时密码", () => withBrowser(async (browser, url) => {
  const admin = await browser.newPage()
  admin.setDefaultTimeout(5000)
  await admin.goto(url + "/users")
  await login(admin)
  const username = "browser.self.reset"
  const original = await createUser(admin, username, "SYSTEM_ADMIN")
  const target = await browser.newPage()
  target.setDefaultTimeout(5000)
  await target.goto(url + "/users")
  await signIn(target, username, original)
  await changeTemporaryPassword(target, original, "self-reset-personal-password")
  await signIn(target, username, "self-reset-personal-password")
  await target.getByRole("row", { name: /browser.self.reset/ }).getByRole("button", { name: /重置密码/ }).click()
  const dialog = target.getByRole("dialog")
  await dialog.getByRole("button", { name: "确认重置" }).click()
  const field = dialog.getByRole("textbox", { name: "临时密码" })
  const replacement = await field.inputValue()
  assert.notEqual(replacement, original)
  await target.evaluate(() => window.dispatchEvent(new Event("focus")))
  await target.getByRole("heading", { name: "登录", exact: true, includeHidden: true }).waitFor()
  assert.equal(await field.inputValue(), replacement)
  await dialog.getByRole("button", { name: "完成" }).click()
  await signIn(target, username, replacement)
  await target.getByRole("heading", { name: "设置个人密码" }).waitFor()
}))
