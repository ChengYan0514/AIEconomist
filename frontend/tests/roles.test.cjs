const assert = require("node:assert/strict")
const { test } = require("node:test")
const { login, withBrowser } = require("./browser.cjs")

test("系统管理员分配自定义角色，权限变更收回已有会话的导出访问", () => withBrowser(async (browser, url) => {
  const admin = await browser.newPage()
  admin.setDefaultTimeout(8000)
  await admin.goto(url + "/roles")
  await login(admin)
  await admin.getByRole("heading", { name: "角色管理" }).waitFor()
  await admin.getByRole("row", { name: /系统管理员.*内置/ }).waitFor()
  await admin.getByRole("link", { name: "新建角色" }).click()
  await admin.getByLabel("角色名称").fill("浏览器论文导出")
  await admin.getByLabel("角色说明").fill("查阅并导出论文")
  await admin.getByText("保存将影响 0 位用户").waitFor()
  const read = admin.getByRole("checkbox", { name: "查阅论文", exact: true })
  await read.focus()
  await read.press("Space")
  await admin.getByRole("checkbox", { name: "导出论文 CSV" }).check()
  await admin.getByText("依赖：查阅论文", { exact: true }).first().waitFor()
  const content = admin.getByRole("checkbox", { name: "查看原件和全文", exact: true })
  await read.uncheck()
  await content.check()
  assert.equal(await admin.getByRole("button", { name: "保存角色" }).isDisabled(), true)
  await content.uncheck()
  await read.check()
  assert.equal(await admin.getByRole("checkbox", { name: "系统管理" }).count(), 0)
  await admin.getByRole("button", { name: "保存角色" }).click()
  await admin.getByRole("heading", { name: "浏览器论文导出" }).waitFor()
  const roleUrl = admin.url()

  await admin.getByRole("link", { name: "用户管理" }).click()
  await admin.getByRole("button", { name: "新建用户" }).click()
  const dialog = admin.getByRole("dialog")
  await dialog.getByLabel("用户名", { exact: true }).fill("browser.role")
  await dialog.getByLabel("显示名称").fill("自定义角色成员")
  await dialog.getByLabel("角色", { exact: true }).selectOption({ label: "浏览器论文导出" })
  await dialog.getByRole("button", { name: "创建账号" }).click()
  const temporary = await dialog.getByRole("textbox", { name: "临时密码" }).inputValue()
  await dialog.getByRole("button", { name: "完成" }).click()
  await admin.getByRole("row", { name: /browser.role.*浏览器论文导出/ }).waitFor()
  await admin.goto(roleUrl)
  await admin.getByRole("row", { name: /自定义角色成员.*browser.role.*启用/ }).waitFor()

  const member = await browser.newPage()
  member.setDefaultTimeout(8000)
  await member.goto(url + "/papers")
  await loginMember(member, temporary)
  await member.getByRole("heading", { name: "设置个人密码" }).waitFor()
  const personal = "custom-role-personal-password"
  await member.getByLabel("临时密码", { exact: true }).fill(temporary)
  await member.getByLabel("新密码", { exact: true }).fill(personal)
  await member.getByRole("button", { name: "保存密码" }).click()
  await loginMember(member, personal)
  await member.getByRole("link", { name: "导出 CSV" }).waitFor()
  const exportPath = url + "/api/papers/export"
  assert.equal((await member.request.get(exportPath)).status(), 200)
  assert.equal((await member.request.get(url + "/api/roles")).status(), 403)
  assert.equal(await member.getByRole("link", { name: "角色管理" }).count(), 0)

  await admin.getByRole("link", { name: "编辑角色" }).click()
  await admin.getByText("保存将影响 1 位用户").waitFor()
  await admin.getByRole("checkbox", { name: "导出论文 CSV" }).uncheck()
  await admin.setViewportSize({ width: 390, height: 844 })
  assert.equal(await admin.evaluate(() => document.documentElement.scrollWidth), 390)
  await admin.getByRole("button", { name: "保存角色" }).click()
  await admin.getByRole("heading", { name: "浏览器论文导出" }).waitFor()
  assert.equal((await member.request.get(exportPath)).status(), 403)
  await member.reload()
  await member.getByRole("heading", { name: "论文库" }).waitFor()
  assert.equal(await member.getByRole("link", { name: "导出 CSV" }).count(), 0)
  await member.goto(url + "/roles")
  await member.getByRole("heading", { name: "无权访问此页面" }).waitFor()

  await admin.setViewportSize({ width: 1280, height: 800 })
  await admin.goto(url + "/audit?objectType=ROLE&objectId=" + new URL(roleUrl).pathname.split("/").at(-1))
  await admin.getByRole("button", { name: "修改角色", exact: true }).click()
  const event = admin.getByRole("region", { name: "事件详情" })
  await event.getByText(/PAPER_CSV_EXPORT.*PAPER_READ/).waitFor()
  await event.getByRole("link", { name: "查看角色" }).click()
  await admin.getByRole("heading", { name: "浏览器论文导出" }).waitFor()

  await admin.getByRole("link", { name: "用户管理" }).click()
  await admin.getByRole("button", { name: "停用 browser.role" }).click()
  await admin.getByRole("button", { name: "确认停用" }).click()
  await admin.getByRole("row", { name: /browser.role/ }).getByRole("cell", { name: "停用", exact: true }).waitFor()
  await admin.goto(roleUrl)
  await admin.getByRole("row", { name: /browser.role.*停用/ }).waitFor()
  assert.equal(await admin.getByRole("button", { name: "删除角色" }).isDisabled(), true)
  await admin.getByRole("link", { name: "用户管理" }).click()
  await admin.getByRole("button", { name: "编辑 browser.role" }).click()
  await dialog.getByLabel("角色", { exact: true }).selectOption("READ_ONLY")
  await dialog.getByRole("button", { name: "保存修改" }).click()
  await admin.getByRole("row", { name: /browser.role.*只读用户.*停用/ }).waitFor()
  await admin.goto(roleUrl)
  await admin.getByRole("button", { name: "删除角色" }).click()
  await admin.getByRole("button", { name: "确认删除" }).click()
  await admin.getByRole("heading", { name: "角色管理" }).waitFor()
  await admin.getByRole("row", { name: /只读用户.*内置/ }).waitFor()
  assert.equal(await admin.getByRole("link", { name: "浏览器论文导出" }).count(), 0)
}))

async function loginMember(page, password) {
  await page.getByLabel("用户名").fill("browser.role")
  await page.getByLabel("密码", { exact: true }).fill(password)
  await page.getByRole("button", { name: "登录管理端" }).click()
}
