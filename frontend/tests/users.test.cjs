const assert = require("node:assert/strict")
const { test } = require("node:test")
const { login, withBrowser } = require("./browser.cjs")

test("系统管理员创建只读用户，用户设置个人密码后查阅论文", () => withBrowser(async (browser, url) => {
  const admin = await browser.newPage()
  admin.setDefaultTimeout(5000)
  await admin.goto(url + "/users")
  await login(admin)
  await admin.getByRole("heading", { name: "用户管理", exact: true }).waitFor({ timeout: 5000 })
  await admin.getByRole("button", { name: "新建用户" }).click()
  const form = admin.getByRole("dialog")
  await form.getByLabel("用户名", { exact: true }).fill("browser.reader")
  await form.getByLabel("显示名称", { exact: true }).fill("浏览器验收用户")
  await form.getByLabel("角色", { exact: true }).selectOption("READ_ONLY")
  await form.getByRole("button", { name: "创建账号" }).click()
  const temporary = form.getByRole("textbox", { name: "临时密码" })
  await temporary.waitFor()
  const password = await temporary.inputValue()
  assert.ok(password.length >= 12)
  await form.getByRole("button", { name: "完成" }).click()
  await admin.getByRole("row", { name: /浏览器验收用户.*browser.reader.*只读用户.*启用/ }).waitFor()
  assert.equal(await admin.getByText(password, { exact: true }).count(), 0)
  await admin.setViewportSize({ width: 390, height: 844 })
  assert.equal(await admin.evaluate(() => document.documentElement.scrollWidth), 390)

  const context = await browser.newContext()
  const reader = await context.newPage()
  reader.setDefaultTimeout(5000)
  await reader.goto(url + "/papers/legacy-001")
  await reader.getByLabel("用户名").fill("browser.reader")
  await reader.getByLabel("密码", { exact: true }).fill(password)
  await reader.getByRole("button", { name: "登录管理端" }).click()
  await reader.getByRole("heading", { name: "设置个人密码" }).waitFor()
  assert.equal(await reader.getByRole("navigation").count(), 0)
  await reader.getByLabel("临时密码", { exact: true }).fill(password)
  await reader.getByLabel("新密码", { exact: true }).fill("browser-personal-password")
  await reader.getByRole("button", { name: "保存密码" }).click()
  await reader.getByLabel("用户名").fill("browser.reader")
  await reader.getByLabel("密码", { exact: true }).fill("browser-personal-password")
  await reader.getByRole("button", { name: "登录管理端" }).click()
  await reader.getByRole("heading", { name: "Legacy paper", exact: true }).waitFor()
  assert.equal(await reader.getByRole("link", { name: "用户管理" }).count(), 0)
  assert.equal(await reader.getByRole("link", { name: "导入与处理" }).count(), 0)
  assert.equal(await reader.getByRole("button", { name: "编辑书目" }).count(), 0)
  await reader.getByRole("button", { name: "全文阅读" }).click()
  await reader.getByText("Existing published text").waitFor()
  await reader.goto(url + "/users")
  await reader.getByRole("heading", { name: "无权访问此页面" }).waitFor()
  await reader.goto(url + "/papers")
  await reader.getByRole("heading", { name: "论文库" }).waitFor()
  assert.equal(await reader.getByRole("link", { name: "导出 CSV" }).count(), 0)
  assert.equal(await reader.getByRole("button", { name: "批量导入" }).count(), 0)

  await admin.setViewportSize({ width: 1280, height: 800 })
  await admin.getByLabel("搜索用户").fill("浏览器验收")
  await admin.getByLabel("筛选角色").selectOption("READ_ONLY")
  await admin.getByLabel("筛选状态").selectOption("ACTIVE")
  await admin.getByRole("button", { name: "查询" }).click()
  await admin.getByRole("button", { name: "编辑 browser.reader" }).click()
  await form.getByLabel("显示名称", { exact: true }).fill("浏览器更新名称")
  await form.getByLabel("角色", { exact: true }).selectOption("DATA_MAINTAINER")
  await form.getByRole("button", { name: "保存修改" }).click()
  await admin.getByText("没有找到用户", { exact: true }).waitFor()
  await admin.getByRole("link", { name: "审计日志" }).click()
  await admin.getByRole("row", { name: /browser.reader/ }).getByRole("button", { name: "变更用户角色" }).click()
  const event = admin.getByRole("region", { name: "事件详情" })
  await event.getByText("数据维护员", { exact: true }).waitFor()
  await event.getByRole("link", { name: "查看用户" }).click()
  await admin.getByRole("row", { name: /浏览器更新名称.*数据维护员/ }).waitFor()

  await reader.reload()
  await reader.getByRole("link", { name: "导入与处理" }).waitFor()
  await reader.getByRole("button", { name: "批量导入" }).waitFor()
  assert.equal(await reader.getByRole("link", { name: "导出 CSV" }).count(), 0)
}))
