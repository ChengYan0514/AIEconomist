const assert = require("node:assert/strict")
const { test } = require("node:test")
const { login, withBrowser } = require("./browser.cjs")

test("AI Economist 品牌贯穿登录和论文工作区", () => withBrowser(async (browser, url) => {
  const page = await browser.newPage()
  await page.goto(url)
  assert.match(await page.title(), /AI Economist/)
  await page.getByRole("heading", { name: "登录", exact: true }).waitFor()
  await page.getByText("AI Economist", { exact: true }).waitFor()
  await login(page)
  await page.getByRole("link", { name: "AI Economist 首页" }).waitFor()
  await page.getByRole("navigation", { name: "管理导航" }).getByRole("link", { name: "论文库" }).click()
  await page.getByRole("heading", { name: "论文库", exact: true }).waitFor()
}))

test("通过论文 ID 查找并阅读缺少原件的历史论文", () => withBrowser(async (browser, url) => {
  const page = await browser.newPage()
  await page.goto(url + "/papers")
  await login(page)
  await page.getByLabel("搜索论文").fill("不存在的论文")
  await page.getByRole("button", { name: "查询", exact: true }).click()
  await page.getByText("没有找到论文", { exact: true }).waitFor()
  await page.getByLabel("搜索论文").fill("legacy-001")
  await page.getByRole("button", { name: "查询", exact: true }).click()
  await page.getByRole("columnheader", { name: "出版来源", exact: true }).waitFor({ timeout: 5000 })
  await page.getByRole("columnheader", { name: "年份", exact: true }).waitFor()
  await page.getByRole("columnheader", { name: "OpenAlex", exact: true }).waitFor()
  const paper = page.getByRole("row").filter({ has: page.getByRole("link", { name: "Legacy paper", exact: true }) })
  for (const content of ["Alice · Bob", "Review of Applied Economics", "2024", "已发布全文", "W009"]) {
    await paper.getByText(content, { exact: true }).waitFor()
  }
  const checkbox = paper.getByRole("checkbox", { name: "选择 Legacy paper" })
  await checkbox.check()
  await page.getByRole("status").filter({ hasText: "已选择 1 篇" }).waitFor()
  await page.getByRole("button", { name: "取消选择" }).click()
  assert.equal(await checkbox.isChecked(), false)
  await paper.getByRole("link", { name: "Legacy paper", exact: true }).click()
  assert.equal(new URL(page.url()).pathname, "/papers/legacy-001")
  await page.getByText("legacy-001", { exact: true }).waitFor()
  await page.getByRole("button", { name: "原始文件", exact: true }).click()
  await page.getByText("原件当前不可读取", { exact: true }).waitFor()
  await page.getByRole("button", { name: "全文阅读", exact: true }).click()
  await page.getByText("Existing published text", { exact: true }).waitFor()
  await page.getByRole("link", { name: "返回论文库" }).click()
  await page.getByLabel("搜索论文").fill("legacy-001")
  await page.getByRole("button", { name: "查询", exact: true }).click()
  await page.getByRole("button", { name: "归档", exact: true }).click()
  await page.getByText("没有归档论文", { exact: true }).waitFor()
  await page.getByRole("button", { name: "论文列表", exact: true }).click()
  await page.getByRole("link", { name: "Legacy paper", exact: true }).waitFor()
}))

test("窄屏可通过键盘打开导航和查看论文表格右侧的列", () => withBrowser(async (browser, url) => {
  const page = await browser.newPage({ viewport: { width: 390, height: 844 } })
  await page.goto(url + "/papers/legacy-001")
  await login(page)
  await page.getByRole("heading", { name: "Legacy paper" }).waitFor()
  const toggle = page.getByRole("button", { name: "导航菜单" })
  await toggle.waitFor({ timeout: 5000 })
  const nav = page.getByRole("navigation", { name: "管理导航" })
  assert.equal(await nav.isVisible(), false)
  await page.keyboard.press("Tab")
  await page.keyboard.press("Tab")
  assert.equal(await toggle.evaluate((element) => element === document.activeElement && element.matches(":focus-visible")), true)
  assert.equal(await toggle.evaluate((element) => getComputedStyle(element).outlineStyle), "solid")
  await page.keyboard.press("Enter")
  await nav.getByRole("link", { name: "论文库" }).click()
  const table = page.getByRole("region", { name: "论文列表表格" })
  await table.focus()
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth), 390)
  await page.keyboard.press("ArrowRight")
  await page.waitForFunction(() => document.activeElement.scrollLeft > 0)
}))
